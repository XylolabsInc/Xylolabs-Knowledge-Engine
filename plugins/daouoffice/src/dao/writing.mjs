/**
 * 문장 하나를 검사해 문제 목록을 돌려준다. 문제가 없으면 빈 배열이다.
 * `label` 은 어느 칸인지 알리려고 메시지에 붙인다.
 */
export function checkWriting(text, label = '') {
  const found = [];
  for (const line of String(text ?? '').split('\n')) {
    if (/^https?:\/\//.test(line.trim())) continue;     // 주소는 산문이 아니다
    for (const [re, what, instead] of BANNED) {
      const m = line.match(re);
      if (!m) continue;
      found.push(`${label ? `${label} ` : ''}${what}: "${m[0]}"${instead ? ` → ${instead}` : ''}`);
    }
  }
  return found;
}

/**
 * `기타` 칸은 **문장이 아니라 항목으로 쓴다.** 결재자는 표를 훑는다.
 *
 *   나쁨  두 건이 2026-01-15 카드 승인 한 줄 12,000원으로 처리되어 한 건으로 작성한다
 *   좋음  2026-01-15 카드 승인 12,000원 한 줄
 *
 * 서술형 종결(`…다`·`…요`)로 끝나는 줄만 잡는다. `배송비 없음`·`환불 미확인`
 * 같은 명사형은 이미 항목이므로 건드리지 않는다. 주소 줄은 건너뛴다.
 */
export function checkNoteStyle(lines) {
  const found = [];
  for (const line of lines ?? []) {
    const t = String(line).trim();
    if (!t || /^https?:\/\//.test(t)) continue;
    if (/(다|요)[.]?$/.test(t)) {
      found.push(`기타 문장형: "${t.slice(0, 40)}…" → 항목으로 줄인다`);
    }
  }
  return found;
}
